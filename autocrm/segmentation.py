#!/usr/bin/env python3
"""AutoCRM — segmentation logic (single source of truth).

Shared by pipeline, validate and tests so band/segment rules never drift apart.
"""
import pandas as pd

# ══════════════════════════════════════════════════════════════════════
# سگمنت‌های سه‌گانه رفتاری — منطق سگمنت‌بندی مشتریان
# ══════════════════════════════════════════════════════════════════════
# این فایل «تک‌مرجع حقیقت» (تک‌مرجع حقیقت) سگمنت‌بندی است:
# هم پایپ‌لاین، هم اعتبارسنج و هم تست‌ها از همین توابع استفاده می‌کنند
# تا قانون سگمنت‌بندی هیچ‌وقت بین این سه فایل مغایرت پیدا نکند.
#
# مفهوم سه‌گانه رفتاری (مدل کلاسیک سگمنت‌بندی مشتری):
#   بُعد یک (تازگی) = چقدر اخیر کاربر فعال بوده؟ → اینجا برچسب تازگی
#   بُعد دو (بسامد) = چقدر پرتکرار از سرویس استفاده می‌کند؟ → باند بسامد
#   بُعد سه (مالی) = چقدر پرداخت کرده؟ → باند مالی
#
# برچسب‌های تازگی (از کانفیگ):
#   تازه        = کاربر فعالِ اخیر (فعالیت در ۳۰ روز گذشته)
#   ولرم         = نه خیلی جدید، نه خیلی قدیمی (۳۰ تا ۹۰ روز)
#   سرد         = مدت‌هاست فعالیتی نداشته (بیش از ۹۰ روز)
#   تازه‌وارد          = تازه ثبت‌نام کرده (کمتر از آستانه روز تازه‌واردی کانفیگ)
#   بدون فعالیت = ثبت‌نام کرده ولی هیچ فعالیتی نداشته
#
# باند بسامد و مالی: کم/متوسط/زیاد (بر اساس آستانه‌های کانفیگ)
# سابقه پرداخت: کاربر تا به حال پرداخت موفق داشته یا نه → مسیر پرداختی/رایگان

VALID_SEGMENTS = {
    # ── سگمنت‌های مسیر «تازه» (فعال اخیر) ──
    "champion",           # پرداخت‌کرده + F بالا + M بالا → بهترین مشتری
    "loyal",              # پرداخت‌کرده + F بالا (ولی پرداختش بالا نیست)
    "active_high_value",  # پرداخت‌کرده + M بالا (ولی استفاده‌اش پرتکرار نیست)
    "active",             # پرداخت‌کرده + F و M معمولی → فعال عادی
    "promising",          # هنوز پرداخت نکرده + استفاده کم → پتانسیل رشد
    "engaged_free",       # هنوز پرداخت نکرده ولی فعال و درگیر سرویس
    # ── سگمنت‌های مسیر «ولرم» (در حال سرد شدن) ──
    "at_risk_high_value", # قبلاً پرداخت‌کرده و باارزش، ولی رکیده → خطر از دست رفتن
    "cooling",            # استفاده‌اش در حال کم شدن است
    "occasional",         # فقط گاه‌گاهی استفاده می‌کند
    # ── سگمنت‌های مسیر «سرد» (رکیده/ازدست‌رفته) ──
    "lost_high_value",    # مشتری باارزشی که عملاً از دست رفته
    "hibernating",        # خفته — ممکن است با تحریک برگردد
    "dormant",            # عملاً غیرفعال
    # ── سگمنت‌های مستقل از باند ──
    "new_user",           # تازه‌وارد — هنوز الگوی رفتاری ندارد
}

def rfm_band(score, thresholds):
    """تبدیل نمره (۰-۵) به باند low/medium/high بر اساس آستانه‌های کانفیگ.

    مشترک بین همه فایل‌ها تا قانون باندبندی همه‌جا یکی باشد:
      score >= high آستانه  → "high"
      score >= medium آستانه → "medium"
      در غیر این صورت        → "low"
    """
    if score >= thresholds["high"]: return "high"
    if score >= thresholds["medium"]: return "medium"
    return "low"

def segment(row):
    """
    تعیین سگمنت نهایی کاربر — درخت تصمیم دومسیره (فیکس A1):
    اول مسیر paid/free بر اساس has_ever_paid تفکیک می‌شود تا کاربرِ
    «هرگز پرداخت نکرده» هیچ‌وقت سگمنت پرداختی نگیرد.

    row باید این ستون‌ها را داشته باشد:
      recency_label (fresh/warm/cold/new/never_active)
      frequency_band (low/medium/high)
      monetary_band  (low/medium/high)
      has_ever_paid  ("yes"/"no")
    """
    label = row["recency_label"]
    f = row["frequency_band"]; m = row["monetary_band"]
    paid = row["has_ever_paid"] == "yes"

    # ── دو حالت ویژه که اصلاً وارد درخت بسامد/مالی نمی‌شوند ──
    if label == "new": return "new_user"            # تازه‌وارد: هنوز داده کافی ندارد
    if label == "never_active": return "dormant"    # هیچ فعالیتی نداشته → غیرفعال

    # ── مسیر سرد: مدت‌هاست غیرفعال ──
    if label == "cold":
        if paid and (f == "high" or m == "high"): return "lost_high_value"
        # کاربر باارزشی که رفته — مهم‌ترین هدف کمپین‌های بازگشت
        if f == "medium" or m == "medium": return "hibernating"
        # هنوز کمی ردپا دارد — با یادآور شاید برگردد
        return "dormant"                             # هیچ نشانه‌ای از حضور ندارد

    # ── مسیر ولرم: در فاصله‌ی خطر (از فعال به رکیده) ──
    if label == "warm":
        if paid and (f == "high" or m == "high"): return "at_risk_high_value"
        # باارزش ولی در حال رکود → اولویت حفظ مشتری
        if f == "medium" or m == "medium": return "cooling"
        # در حال سرد شدن → مداخله به‌موقع می‌تواند برگرداندش
        return "occasional"                          # فقط مصرف‌کننده گاه‌به‌گاه

    # ── مسیر تازه: فعال اخیر (کارت‌های برنده و پتانسیل‌ها) ──
    if not paid:
        # هنوز پرداخت نکرده: اگر خوب درگیر شده جای رشد دارد، وگرنه تازه‌کار
        return "engaged_free" if f in ("medium", "high") else "promising"
    if f == "high" and m == "high": return "champion"           # مشتری ایده‌آل
    if f == "high": return "loyal"                              # وفادارِ پراستفاده
    if m == "high": return "active_high_value"                  # پرداخت‌کننده بزرگ
    return "active"                                             # فعال عادی

def apply_segments(df):
    """روی جدول کامل: ستون سگمنت را از روی باند‌ها و برچسب‌ها می‌سازد.

    استفاده در پایپ‌لاین بعد از ساخت برچسب تازگی و باندهای بسامد/مالی.
    کپی گرفتن از جدول برای جلوگیری از تغییر ناخواسته جدول اصلی است.
    """
    df = df.copy()
    df["rfm_segment"] = df.apply(segment, axis=1)
    return df
